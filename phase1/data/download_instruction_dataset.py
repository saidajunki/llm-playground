                ("長い", "短いです"),
                ("明るい", "暗いです"),
                ("熱い", "冷たいです"),
                ("速い", "遅いです"),
                ("新しい", "古いです"),
                ("重い", "軽いです"),
                ("広い", "狭いです"),
