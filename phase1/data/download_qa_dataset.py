def save_qa_dataset(qa_pairs, output_path):
    """Q&Aデータセットをファイルに保存"""
    with open(output_path, 'w', encoding='utf-8') as f:
        for q, a in qa_pairs:
            f.write(f"{q}\t{a}\n")
    print(f"保存完了: {output_path}")
    print(f"Q&Aペア数: {len(qa_pairs)}")


