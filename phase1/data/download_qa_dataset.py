def expand_qa_pairs(base_pairs, target_count=10000):
    """Q&Aペアを拡張して目標数に近づける"""
    import random
    
    expanded = list(base_pairs)
    
    # 質問のバリエーションを生成
    question_prefixes = [
        "", "教えてください、", "質問です。", "知りたいのですが、",
        "すみません、", "ちょっと聞きたいのですが、"
    ]
    
    question_suffixes = [
        "", "教えてください。", "知りたいです。", "お願いします。"
    ]
    
    # 回答のバリエーション
    answer_prefixes = [
        "", "はい、", "答えは、", "それは、"
    ]
    
    while len(expanded) < target_count:
        q, a = random.choice(base_pairs)
        
        # バリエーションを追加
        new_q = random.choice(question_prefixes) + q
        if not new_q.endswith("か") and not new_q.endswith("。"):
            new_q += random.choice(question_suffixes)
        
        new_a = random.choice(answer_prefixes) + a
        
        expanded.append((new_q, new_a))
    
    return expanded[:target_count]


